"""Merge reviewed feature catalogs and generate legacy presentation adapters.

Run before flutter gen-l10n. Source values used in parsing/persistence stay intact;
only callers explicitly requesting displayText use this adapter.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
catalogs = {}
for locale in ('zh', 'en'):
    catalog = {'@@locale': locale}
    for file in sorted(HERE.glob(f'*_{locale}.json')):
        for key, value in json.loads(file.read_text()).items():
            if key.startswith('@@'):
                continue
            if key in catalog:
                raise ValueError(f'Duplicate key {key} in {file}')
            catalog[key] = value
    catalogs[locale] = catalog
    (ROOT / f'lib/l10n/app_{locale}.arb').write_text(
        json.dumps(catalog, ensure_ascii=False, indent=2) + '\n')
zh, en = catalogs['zh'], catalogs['en']
assert {k for k in zh if not k.startswith('@')} == {k for k in en if not k.startswith('@')}, 'Translation key mismatch'

def dart_string(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')

lines = [
    '// Generated by tool/localization/generate.py; do not edit.',
    "import 'app_localizations.dart';",
    '',
    'String? catalogDisplayText(String source, AppLocalizations strings,',
    '    String Function(String) translateArgument) {',
    '  switch (source) {',
]
seen = set()
patterns = []
for key, value in zh.items():
    if key.startswith('@') or value in seen:
        continue
    seen.add(value)
    meta = zh.get('@' + key, {}).get('placeholders', {})
    if not meta:
        lines.append(f'    case {dart_string(value)}: return strings.{key};')
        continue
    names = re.findall(r'\{(\w+)\}', value)
    if set(names) != set(meta) or len(names) != len(set(names)):
        continue  # ICU selections/plurals are called through typed accessors.
    pattern = '^'
    position = 0
    for match in re.finditer(r'\{(\w+)\}', value):
        pattern += re.escape(value[position:match.start()]) + r'([\s\S]*?)'
        position = match.end()
    pattern += re.escape(value[position:]) + '$'
    args = []
    for name, details in meta.items():
        arg = f'match.group({names.index(name)+1})!'
        kind = details.get('type', 'Object')
        if kind in ('int', 'double', 'num'):
            arg = f'{kind}.tryParse({arg})'
        elif kind == 'DateTime':
            break
        else:
            arg = f'translateArgument({arg})'
        args.append((arg, kind))
    else:
        patterns.append((len(value), key, pattern, args))
lines += ['  }']
for _, key, pattern, args in sorted(patterns, reverse=True):
    lines += ['  {', f'    final match = RegExp({dart_string(pattern)}).firstMatch(source);', '    if (match != null) {']
    for index, (arg, kind) in enumerate(args):
        lines.append(f'      final arg{index} = {arg};')
    nullable = [f'arg{i} != null' for i, (_, kind) in enumerate(args) if kind in ('int', 'double', 'num')]
    if nullable:
        lines.append('      if (' + ' && '.join(nullable) + ') {')
    lines.append(f'      return strings.{key}(' + ', '.join(f'arg{i}' for i in range(len(args))) + ');')
    if nullable:
        lines.append('      }')
    lines += ['    }', '  }']
lines += ['  return null;', '}']
(ROOT / 'lib/l10n/catalog_display.dart').write_text('\n'.join(lines) + '\n')
print(f'Generated {sum(not k.startswith("@") for k in zh)} bilingual messages.')
